  const first = await createEntity(project.id, { name: '沈砚', entity_type: 'character', summary: '所选对象的依据', status: 'canonical' })
  const second = await createEntity(project.id, { name: '船医', entity_type: 'character', summary: '未选择的独立资料', status: 'canonical' })
  await openProjectWorkbench(project, 'world', 'objects')
