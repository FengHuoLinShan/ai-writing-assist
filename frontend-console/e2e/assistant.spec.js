for (const width of [1280, 390]) test(`临时正文讨论、保存后重新绑定且旧轮次保持原目标 · ${width}px`, async ({ page, projectFactory, openProjectWorkbench, browserErrors }, testInfo) => {
  await page.setViewportSize({ width, height: 844 })
  const project = await projectFactory({ title: '临时讨论验收' })
  const original = '已保存原稿：灯亮着。'
  const saved = await createAutosavedDraft(project.id, 1, '临时讨论验收', original)
  const base = saved.draft || saved
  await openProjectWorkbench(project, 'writing')
  await page.evaluate(() => window.router.navigate('writing', null, true, new URLSearchParams({ chapter_index: '1' })))
  await waitWritingReady(page, { editor: true })
  const editor = page.locator('#writing-editor')
  await expect(editor).toHaveValue(original)
  let releaseSave
  const saveReady = new Promise(resolve => { releaseSave = resolve })
  const pendingSave = async route => {
    if (route.request().method() === 'PUT') await saveReady
    await route.continue()
  }
  const saveUrl = `**/api/writing/drafts/${base.id}?*`
  await page.route(saveUrl, pendingSave)
  try {
    const temporary = '尚未保存的句子：灯😀忽然熄灭。'
    await editor.fill(temporary)
    await editor.evaluate(element => element.setSelectionRange(0, element.value.length))
    await page.getByRole('button', { name: '修改这里', exact: true }).click()
    const panel = page.locator('#project-assistant-panel')
    await panel.locator('#assistant-input').fill('临时讨论验收：先讨论措辞，不正式修改。')
    async function send() {
      const submitted = page.waitForResponse(response => response.url().includes('/turns') && response.request().method() === 'POST')
      await panel.getByRole('button', { name: '发送', exact: true }).click()
      const response = await submitted
      expect(response.status()).toBe(202)
      const run = await response.json()
      let completed
      await expect.poll(async () => {
        completed = await (await page.request.get(`${API_BASE}/assistant/runs/${run.id}?novel_id=${project.id}`)).json()
        return completed.status
      }, { timeout: 30000 }).toBe('completed')
      expect(completed.result.actions).toEqual([])
      return completed
    }
    const first = await send()
    expect(first.context.temporary_draft_id).toBeTruthy()
    expect(first.context.selection).toBe(temporary)
    for (const field of ['draft_id', 'source_hash', 'selection_start', 'selection_end']) expect(first.context[field]).toBeFalsy()
    const serverBeforeSave = await (await page.request.get(`${API_BASE}/writing/chapters/1/draft?novel_id=${project.id}`)).json()
    expect((serverBeforeSave.draft || serverBeforeSave).content).toBe(original)
    await expect(panel.getByRole('button', { name: '确认所选修改' })).toHaveCount(0)
    await page.screenshot({ path: testInfo.outputPath(`temporary-discussion-${width}.png`), fullPage: true })
    await panel.getByRole('button', { name: '关闭项目助手', exact: true }).click()
    releaseSave()
    await expect(editor).toHaveValue(temporary)
    await page.locator('#btn-autosave').click()
    await expect(page.locator('#writing-save-status')).toHaveText('已保存到工作稿')
    await page.unroute(saveUrl, pendingSave)
    await editor.evaluate(element => element.setSelectionRange(0, element.value.length))
    await page.getByRole('button', { name: '修改这里', exact: true }).click()
    await panel.locator('#assistant-input').fill('临时讨论验收：已保存，重新核对当前版本。')
    const next = await send()
    expect(next.context.temporary_draft_id).toBeFalsy()
    expect(next.context.draft_id).toBeTruthy()
    expect(next.context.source_hash).toBeTruthy()
    expect(next.context.selection).toBe(temporary)
    const old = await (await page.request.get(`${API_BASE}/assistant/runs/${first.id}?novel_id=${project.id}`)).json()
    expect(old.context).toEqual(first.context)
    expect(browserErrors).toEqual([])
  } finally {
    releaseSave()
    await page.unrouteAll({ behavior: 'wait' })
  }
})

