async function openDossier(page) {
  await page.getByRole('tab', { name: '设定档案', exact: true }).click()
  const section = page.locator("details.world-entity-dossier")
  if (await section.getAttribute("open") === null) await section.locator("summary").click()
  const editor = section.locator(".object-dossier-editor")
  await expect(editor.getByRole("button", { name: "保存档案条目", exact: true })).toBeVisible()
  return editor
}

