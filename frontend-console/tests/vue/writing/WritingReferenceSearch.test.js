import { afterEach, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import WritingReferenceSearch from '../../../vue/views/writing/components/WritingReferenceSearch.vue'
import { resetBridgeOverrides, setBridgeOverrides } from '../../../vue/bridge/index.js'

afterEach(resetBridgeOverrides)

it('searches only the current work, opens the selected object and reports the page boundary', async () => {
  const listEntities = vi.fn().mockResolvedValue({ items: [{ id: 'one', name: '沈砚', summary: '医师' }], total: 30 })
  setBridgeOverrides({ api: { world: { listEntities } } })
  const wrapper = mount(WritingReferenceSearch, { props: { projectId: 'first' } })
  await wrapper.setProps({ selection: '沈砚' })
  await wrapper.get('form').trigger('submit')
  await flushPromises()
  expect(listEntities).toHaveBeenCalledWith({ novel_id: 'first', q: '沈砚', skip: 0, limit: 20 })
  expect(wrapper.text()).toContain('当前展示前 20 个匹配对象')
  await wrapper.findAll('button').find(button => button.text() === '沈砚').trigger('click')
  expect(wrapper.emitted('open-object')).toEqual([['one']])
  wrapper.unmount()
})

it('discards late results from another work and retains input on failure', async () => {
  let resolve
  const listEntities = vi.fn().mockImplementationOnce(() => new Promise(done => { resolve = done }))
    .mockRejectedValueOnce(new Error('网络失败'))
  setBridgeOverrides({ api: { world: { listEntities } } })
  const wrapper = mount(WritingReferenceSearch, { props: { projectId: 'first' } })
  await wrapper.get('input').setValue('旧查询')
  await wrapper.get('form').trigger('submit')
  await wrapper.setProps({ projectId: 'second' })
  resolve({ items: [{ id: 'old', name: '旧作品对象' }], total: 1 })
  await flushPromises()
  expect(wrapper.text()).not.toContain('旧作品对象')
  await wrapper.get('input').setValue('新查询')
  await wrapper.get('form').trigger('submit')
  await flushPromises()
  expect(wrapper.get('[role=alert]').text()).toBe('网络失败')
  expect(wrapper.get('input').element.value).toBe('新查询')
  wrapper.unmount()
})

it('pins only reference identities, rechecks after remount and isolates accounts and works', async () => {
  localStorage.clear()
  const listEntities = vi.fn().mockResolvedValue({ items: [{ id: 'one', name: '沈砚', summary: '不应写入备份的简介' }], total: 1 })
  const getEntity = vi.fn().mockResolvedValue({ id: 'one', name: '沈砚', summary: '当前已保存简介' })
  setBridgeOverrides({ api: { world: { listEntities, getEntity } }, currentAccount: { id: 'a' } })
  let wrapper = mount(WritingReferenceSearch, { props: { projectId: 'first' } })
  await wrapper.get('input').setValue('沈砚')
  await wrapper.get('form').trigger('submit'); await flushPromises()
  await wrapper.findAll('button').find(b => b.text() === '固定参考：沈砚').trigger('click'); await flushPromises()
  expect(wrapper.get('[aria-label="固定参考"]').text()).toContain('当前已保存简介')
  const stored = Object.values(localStorage).join('')
  expect(stored).toContain('"id":"one"')
  expect(stored).not.toContain('简介')
  wrapper.unmount()
  getEntity.mockRejectedValueOnce(new Error('资料版本不可用'))
  wrapper = mount(WritingReferenceSearch, { props: { projectId: 'first' } }); await flushPromises()
  expect(wrapper.get('[aria-label="固定参考"]').text()).toContain('资料版本不可用')
  await wrapper.setProps({ projectId: 'second' }); await flushPromises()
  expect(wrapper.find('[aria-label="固定参考"]').exists()).toBe(false)
  wrapper.unmount()
  setBridgeOverrides({ currentAccount: { id: 'b' } })
  wrapper = mount(WritingReferenceSearch, { props: { projectId: 'first' } }); await flushPromises()
  expect(wrapper.find('[aria-label="固定参考"]').exists()).toBe(false)
  wrapper.unmount(); localStorage.clear()
})

it('searches only saved earlier chapters through literal Evidence and rechecks the exact source before showing it', async () => {
  const ref = { draft_id: 'draft', chapter_index: 1, version_number: 1, content_mode: 'working', start_offset: 0, end_offset: 2, source_hash: 'a'.repeat(64), range_hash: 'b'.repeat(64) }
  const grepEvidence = vi.fn().mockResolvedValue({ hits: [{ title: '第 1 章', snippet: '旧船', source_ref: ref }], total: 1, warnings: ['仅字面检索'] })
  const readEvidence = vi.fn().mockResolvedValue({ source_ref: ref, text: '核对后的原文', warnings: [] })
  setBridgeOverrides({ api: { context: { grepEvidence, readEvidence } } })
  const wrapper = mount(WritingReferenceSearch, { props: { projectId: 'first', chapterIndex: 2 } })
  await wrapper.get('select').setValue('previous'); await wrapper.get('input').setValue('旧船')
  await wrapper.get('form').trigger('submit'); await flushPromises()
  expect(grepEvidence).toHaveBeenCalledWith(expect.objectContaining({ novel_id: 'first', pattern: '旧船', chapter_to: 1, content_mode: 'working', limit: 20 }))
  await wrapper.findAll('button').find(b => b.text() === '核对原文').trigger('click'); await flushPromises()
  expect(readEvidence).toHaveBeenCalledWith(expect.objectContaining({ novel_id: 'first', source_ref: ref }))
  expect(wrapper.get('[aria-label="核对原文"]').text()).toContain('核对后的原文')
  await wrapper.setProps({ chapterIndex: 1 })
  expect(wrapper.find('[aria-label="核对原文"]').exists()).toBe(false)
  await wrapper.get('form').trigger('submit')
  expect(wrapper.get('[role=alert]').text()).toContain('还没有章节')
  expect(grepEvidence).toHaveBeenCalledTimes(1)
  wrapper.unmount()
})

it('reports a local reference backup failure without discarding the current reference', async () => {
  setBridgeOverrides({ currentAccount: { id: 'a' }, localDraftStorage: { getItem: () => null, setItem: () => { throw new Error('full') } }, api: { world: { listEntities: async () => ({ items: [{ id: 'one', name: '沈砚' }] }), getEntity: async () => ({ name: '沈砚', summary: '保留当前参考' }) } } })
  const wrapper = mount(WritingReferenceSearch, { props: { projectId: 'first' } })
  await wrapper.get('input').setValue('沈砚'); await wrapper.get('form').trigger('submit'); await flushPromises()
  await wrapper.findAll('button').find(b => b.text() === '固定参考：沈砚').trigger('click'); await flushPromises()
  expect(wrapper.text()).toContain('未能备份')
  expect(wrapper.get('[aria-label="固定参考"]').text()).toContain('保留当前参考')
  wrapper.unmount()
})
